using UnityEngine;

/// <summary>
/// 경직력을 누적해 경직에 걸릴 수 있는 대상입니다.
/// </summary>
/// <remarks>
/// 때리는 쪽(총기·근접)은 실어 보낼 <b>경직력</b>만 알려 주고, 그것이 경직으로 이어지는지는 받는 쪽이 정합니다.
/// 누적치·한계치·면역 윈도우를 모두 받는 쪽이 소유하므로, 무기는 대상이 얼마나 잘 버티는지 몰라도 됩니다.
///
/// <see cref="IDamageable"/>과 분리한 이유는 피해와 경직이 독립적이기 때문입니다.
/// 피해 0인 견제 사격이나 경직력 0인 피해가 모두 성립합니다.
/// 같은 이유로 <see cref="IKnockbackReceiver"/>와도 분리합니다. 넉백은 "얼마나 밀리는가"이고
/// 경직은 "행동이 끊기는가"라서, 한쪽만 있는 공격이 자연스럽게 표현됩니다.
///
/// <b>구현하지 않은 대상은 경직이 없습니다.</b> 경직력 인자는 조용히 무시되며 피해만 들어갑니다.
/// 플레이어와 다운 아군이 여기 해당합니다(설계 문서 §2 — 경직은 감염체 전용).
/// </remarks>
public interface IStaggerable
{
    /// <summary>
    /// 경직력을 누적하고, 한계치에 닿았으면 경직을 발동합니다.
    /// </summary>
    /// <param name="staggerPower">이번 공격이 더할 경직력입니다. 0 이하면 아무것도 하지 않습니다.</param>
    /// <returns>이번 누적으로 경직이 실제로 발동했으면 true입니다. 누적만 됐으면 false입니다.</returns>
    /// <remarks>
    /// 면역 윈도우 안이거나 이미 경직 중이면 누적하지 않고 false를 돌려줍니다.
    /// 반환값은 "쌓였는가"가 아니라 "터졌는가"입니다. 호출부가 발동 순간에만 연출을 붙일 수 있게 하기 위한 구분입니다.
    /// </remarks>
    bool ApplyStagger(float staggerPower);
}
