/// <summary>
/// 감염체 종류의 고정 식별자입니다.
/// </summary>
/// <remarks>
/// 시체 처리처럼 종류마다 다른 설정을 고를 때의 키로 씁니다.
/// 값을 명시하는 이유는 나중에 멤버가 중간에 끼어들어도 이미 저장된 프리팹과 씬의 선택이
/// 다른 종류로 밀리지 않게 하기 위해서입니다. 이름만 바꾸는 것은 값이 유지되므로 안전합니다.
/// </remarks>
public enum EnemyType
{
    /// <summary>종류를 아직 지정하지 않은 상태입니다.</summary>
    Unknown = 0,

    /// <summary>하울링으로 주변 개체를 불러 모으는 기본 감염체입니다.</summary>
    Howler = 1
}
